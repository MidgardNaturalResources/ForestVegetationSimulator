     & 143, 321, 322, 475, 
     & 803, 810, 814, 843/

      DATA (WoodlandEqs(I), I=1,16) /
     & "R03CHO0065", "R03CHO0066", "R03CHO0065", "R03CHO0066", 
     & "R03CHO0065", "R03CHO0106", "400DVEW133", "R03CHO0106",
     & "R03CHO0106", "200DVEW475", "200DVEW814", "200DVEW475",
     & "300DVEW800", "300DVEW800", "200DVEW814", "300DVEW800" /

        IF (ECOREG.EQ.'') THEN
          ECOREG = '0000'
          CALL ERRGRO(.TRUE., 43)
        END IF

        idx = 0
        igroup = 0
        validDivSpp = .FALSE.
        SppFound = .FALSE.
        JenkinsGrp = .FALSE.
        useSppCode = .FALSE.

        DivSplit = '0000'
        DIVISION = ECOREG
        
        DO i=1, size(DIVS)
          IF (adjustl(DIVS(i)) .EQ. DIVISION) idx = i
        END DO

          ! Improvement suggestion: Make this a binary search to speed up processing time
          do i= 1,size(SPPDIV, dim= 1)
            if ( SPPDIV(i,1) .EQ. SPCD) THEN 
                SppFound = .TRUE.
                useSppCode = .TRUE.
                if (idx.gt.0) THEN 
                  if ( SPPDIV(i,idx+1).EQ. 1) validDivSpp = .TRUE.
                end if
                exit
            end if
          end do

        if (.NOT.SppFound) then
          do i =1,size(JenkinsSpp, dim=1)
            if (JenkinsSpp(i,1).EQ.SPCD) then
              igroup = JenkinsSpp(i,2)
              SppFound = .TRUE.
              JenkinsGrp = .TRUE.
              exit
            end if
          end do
        end if

        ! If SppFound, species is not woodland and uses NVB species
        !   or Jenkins group code
      if (SppFound) then
        if (validDivSpp) then
          DIVISION = ADJUSTL(DIVISION)
          IF (LEN_TRIM(DIVISION) .LT. 4) DIVISION ='0'//TRIM(DIVISION)
          DivSplit = TRIM(DIVISION)
        end if

        if (useSppCode) then
          write(SppID, FMT='(I4)') SPCD
        else if (JenkinsGrp) then
          write(SppID, FMT='(I4)') igroup
        end if

        SppID = ADJUSTL(SppID)

        DO WHILE (LEN_TRIM(SppID) .LT. 3)
          SppID = '0' // TRIM(SppID)
        END DO

        VOLEQ = 'NVB' // DivSplit // TRIM(SppID)

C       Check for managed plantation
        IF((DivSplit .EQ.'0000' .OR. DivSplit .EQ. '0230').AND. 
     &      (SPCD .EQ. 111 .OR. SPCD .EQ. 131) 
     &       .AND. ISTDORG .EQ. 1) THEN
         VOLEQ(11:11) = 'P'
        END IF

      else
        if (ISTATE.eq.0) CALL ERRGRO(.TRUE., 44)
        do i= 1, size(WoodlandSpp)
          if(WoodlandSpp(i).eq.SPCD) THEN 
            VOLEQ=WoodlandEqs(i)
            exit
          end if
        end do
        if (ISTATE.eq.6 .or. ISTATE.eq.41 .or. ISTATE.eq.53) THEN
          if(SPCD.eq.62 .or. SPCD.eq.65)   VOLEQ='400DVEW065'
          if(SPCD.eq.66)                   VOLEQ='200DVEW066'
          if(SPCD.eq.322)                  VOLEQ='200DVEW475'
        else if (ISTATE.eq.4 .or. ISTATE.eq.35) THEN
          if(SPCD.eq.332 .or. SPCD.eq.814) VOLEQ='300DVEW800'
        end if
      end if
        
      return 
